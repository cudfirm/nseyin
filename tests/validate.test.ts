import { validateBooking, validateContact, looksLikeBot, escapeHtml, lagosToday, clean } from '../supabase/functions/_shared/validate.ts';
let pass=0, fail=0; const t=(n:string,c:boolean,x:any='')=>{c?pass++:fail++; console.log((c?'PASS ':'FAIL ')+n+(c?'':'  '+JSON.stringify(x)));};
const now=Date.parse('2026-10-17T10:00:00Z'); const day=(n:number)=>new Date(now+n*864e5+36e5).toISOString().slice(0,10);
const good={idempotencyKey:'11111111-1111-4111-8111-111111111111',service:'swedish',duration:'60',location:'workspace',name:'Ada Obi',email:'ada@example.com',phone:'+234 801 234 5678',contactMethod:'email',date:day(3),time:'evening',message:'',acceptedTerms:true,acknowledgedBoundaries:true};
t('valid booking passes', validateBooking(good,now).ok, validateBooking(good,now).errors);
const bad=(patch:any,key:string,name:string)=>{const r=validateBooking({...good,...patch},now); t(name, !r.ok && key in r.errors, r.errors);};
bad({service:'hot-stone'},'service','unknown service rejected');
bad({name:'A'},'name','short name rejected');
bad({email:'a@b'},'email','bad email rejected');
bad({email:'a@b.com\nBcc: x@y.com'},'email','email header injection rejected');
bad({phone:'abc'},'phone','letters in phone rejected');
bad({phone:'123'},'phone','short phone rejected');
bad({contactMethod:'sms'},'contactMethod','bad contact method rejected');
bad({date:'2020-01-01'},'date','past date rejected');
bad({date:'2027-06-01'},'date','date >4 months rejected');
bad({date:'2026-02-30'},'date','impossible date rejected');
bad({date:'17/10/2026'},'date','wrong date format rejected');
bad({time:'midnight'},'time','bad time rejected');
bad({message:'x'.repeat(601)},'message','long message rejected');
bad({acceptedTerms:false},'terms','terms required');
bad({acknowledgedBoundaries:'true'},'boundaries','boundaries must be boolean true');
bad({idempotencyKey:'nope'},'idempotencyKey','bad idempotency key rejected');
t('today allowed (Lagos)', validateBooking({...good,date:lagosToday(now)},now).ok);
t('control chars stripped', clean('a\u0000b\u0007c',10)==='abc');
t('name newlines collapsed', validateBooking({...good,name:'Ada\nObi'},now).value.name==='Ada Obi');
t('non-object body safe', !validateBooking(null,now).ok && !validateBooking('x',now).ok);
t('honeypot flagged', looksLikeBot({website:'http://spam'}));
t('too-fast flagged', looksLikeBot({elapsedMs:900}));
t('normal human passes bot check', !looksLikeBot({website:'',elapsedMs:45000}));
t('duration required', 'duration' in validateBooking({...good,duration:''},now).errors);
t('bad duration rejected', 'duration' in validateBooking({...good,duration:'45'},now).errors);
t('location required', 'location' in validateBooking({...good,location:''},now).errors);
t('bad location rejected', 'location' in validateBooking({...good,location:'beach'},now).errors);
t('custom + suite valid', validateBooking({...good,duration:'custom',location:'suite'},now).ok);
t('html escaped', escapeHtml('<script>"x"&\'</script>')==='&lt;script&gt;&quot;x&quot;&amp;&#39;&lt;/script&gt;');
t('contact valid', validateContact({idempotencyKey:good.idempotencyKey,name:'Ada',email:'a@b.co',message:'Hello there, a question'}).ok);
t('contact short msg', 'message' in validateContact({idempotencyKey:good.idempotencyKey,name:'Ada',email:'a@b.co',message:'hi'}).errors);
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail?1:0);
